export function normalizeLanguage(language) {
  const normalized = String(language || "").trim().toLowerCase();
  if (normalized.startsWith("zh")) return "zh-CN";
  if (normalized.startsWith("en")) return "en-US";
  if (normalized.startsWith("ru")) return "ru-RU";
  return DEFAULT_LANGUAGE;
}

export function toIntlLocale(language = DEFAULT_LANGUAGE) {
  const normalized = normalizeLanguage(language);
  if (normalized === "en-US") return "en-US";
  if (normalized === "ru-RU") return "ru-RU";
  return "zh-CN";
}

export function detectInitialLanguage() {
  if (typeof window !== "undefined") {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored) return normalizeLanguage(stored);

    const browserLanguage = window.navigator?.languages?.[0] || window.navigator?.language;
    if (browserLanguage) return normalizeLanguage(browserLanguage);
  }
  return DEFAULT_LANGUAGE;
}

export function translateSourceText(source, language = DEFAULT_LANGUAGE) {
  if (!source || language === "zh-CN") return source;

  const text = String(source);
  if (exactMap[text]?.[language]) return exactMap[text][language];

  const standaloneLabel = translateStandaloneLabel(text, language);
  if (standaloneLabel) return standaloneLabel;

  if (text.includes("｜")) {
    return text.split("｜").map((part) => translateSourceText(part.trim(), language)).join(" | ");
  }

  if (text.includes("|")) {
    return text.split("|").map((part) => translateSourceText(part.trim(), language)).join(" | ");
  }

  if (text.includes("或")) {
    const joiner = language === "en-US" ? " or " : " или ";
    return text.split("或").map((part) => translateSourceText(part.trim(), language)).join(joiner);
  }

  const labelTranslation = translateByLabel(text, language);
  if (labelTranslation) return labelTranslation;

  const labelPrefixTranslation = translateLabelPrefix(text, language);
  if (labelPrefixTranslation) return labelPrefixTranslation;

  for (const [pattern, render] of dynamicRules) {
    const match = text.match(pattern);
    if (match) return render(language, match);
  }

  return text;
}

export function buildLanguageResources(language) {
  const translation = {};

  Object.entries(interfaceMap).forEach(([key, values]) => {
    translation[key] = values[language] || values[DEFAULT_LANGUAGE];
  });

  exactEntries.forEach(([zh, en, ru]) => {
    translation[zh] = language === "zh-CN" ? zh : language === "en-US" ? en : ru;
  });

  labelEntries.forEach(([zh, en, ru]) => {
    translation[zh] = language === "zh-CN" ? zh : language === "en-US" ? en : ru;
  });

  return translation;
}

